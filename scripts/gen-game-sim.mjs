// Generates core/game-sim/game.bundle.mjs — the game's OWN harvest code, bundled for the tracker.
//
// Since the game rolls every harvest from a seeded PRNG (src/lib/prng.ts: farm id + the farm's
// activity counter for that node type + the critical-hit name), what the next chop / mine / harvest
// gives is fixed before you click — sfl.world shows it per node. Re-implementing each yield by hand
// drifted (a +0.1 here, a missed boost there), so the tracker runs the game's reducers instead:
// core/engine/harvest-sim.mjs replays every node's next harvest on a copy of the farm, in the order
// they become ready, and reads the yield off the inventory. Same code, same numbers.
//
// Regenerate when the game changes (a new boost, a new node type):
//   node scripts/gen-game-sim.mjs [path to a sunflower-land checkout]
// Default checkout: ../sunflower-land (branch with upstream main checked out).
//
// The game is a browser app: images become empty modules, and the few globals it touches at import
// time (localStorage, document, navigator for i18n) are stubbed in the bundle's banner. Lives outside
// api/ — Vercel would count it as a serverless function.
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GAME = path.resolve(process.argv[2] || path.join(ROOT, "..", "sunflower-land"));
const OUT = path.join(ROOT, "core", "game-sim", "game.bundle.mjs");
const ENTRY = path.join(GAME, "src", "__tracker_sim_entry.ts");

const entry = `
export { makeGame } from "features/game/lib/transforms";
export { KNOWN_IDS } from "features/game/types";
export { CROPS } from "features/game/types/crops";
export { chop, getTreeReadyAt } from "features/game/events/landExpansion/chop";
export { mineStone } from "features/game/events/landExpansion/stoneMine";
export { mineIron } from "features/game/events/landExpansion/ironMine";
export { mineGold } from "features/game/events/landExpansion/mineGold";
export { mineCrimstone } from "features/game/events/landExpansion/mineCrimstone";
export { getMineReadyAt } from "features/game/lib/resourceNodes";
export { drillOilReserve, getOilReserveReadyAt } from "features/game/events/landExpansion/drillOilReserve";
export { harvest, getCropReadyAt } from "features/game/events/landExpansion/harvest";
export { harvestFruit } from "features/game/events/landExpansion/fruitHarvested";
export { getFruitReadyAt } from "features/game/events/landExpansion/fruitPatchReadiness";
export { harvestGreenHouse } from "features/game/events/landExpansion/harvestGreenHouse";
export { getGreenhousePotReadyAt } from "features/game/events/landExpansion/greenhouseReadiness";
export { harvestFlower } from "features/game/events/landExpansion/harvestFlower";
export { getFlowerReadyAt } from "features/game/lib/flowerBedReadiness";
`;

const banner = [
  "const __m=new Map();const __el=()=>({setAttribute(){},getAttribute(){return null},style:{},classList:{add(){},remove(){},contains(){return false}},appendChild(){},addEventListener(){},removeEventListener(){}});",
  "globalThis.localStorage??={getItem:(k)=>__m.get(k)??null,setItem:(k,v)=>__m.set(k,String(v)),removeItem:(k)=>__m.delete(k),clear:()=>__m.clear()};",
  "globalThis.sessionStorage??=globalThis.localStorage;",
  "globalThis.document??={documentElement:__el(),body:__el(),head:__el(),createElement:__el,getElementById:()=>null,querySelector:()=>null,addEventListener(){},cookie:''};",
  "globalThis.navigator??={language:'en',userAgent:'node'};",
].join("");

const commit = execFileSync("git", ["-C", GAME, "log", "-1", "--format=%h %cs %s"], { encoding: "utf8" }).trim();
// The game checkout's own esbuild, through its JS API (no shell quoting of the banner).
const esbuild = createRequire(path.join(GAME, "package.json"))("esbuild");
fs.writeFileSync(ENTRY, entry);
try {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  await esbuild.build({
    entryPoints: [ENTRY], bundle: true, platform: "node", format: "esm", minify: true, outfile: OUT,
    tsconfig: path.join(GAME, "tsconfig.json"), absWorkingDir: GAME, logLevel: "error",
    loader: Object.fromEntries(["png", "webp", "gif", "jpg", "jpeg", "svg", "mp3", "wav", "ogg", "mp4"].map((e) => [`.${e}`, "empty"])),
    define: { "import.meta.env": JSON.stringify({ VITE_NETWORK: "mainnet" }) },
    banner: { js: `// GENERATED by scripts/gen-game-sim.mjs from sunflower-land ${commit} — do not hand-edit.
${banner}` },
  });
} finally {
  fs.rmSync(ENTRY, { force: true });
}
console.log(`wrote ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1e6).toFixed(1)} MB) from ${commit}`);
